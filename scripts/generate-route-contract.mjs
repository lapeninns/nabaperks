// Route-contract generator — derives a committed catalogue of the app's HTTP
// surface (pages, route handlers + their methods, and server-action modules)
// straight from the App Router file tree. Run with `--check` in CI to fail when
// docs/ROUTES.md has drifted from the code; run with no args to regenerate it.
import { readFileSync, writeFileSync } from "node:fs"
import { spawnSync } from "node:child_process"

const OUTPUT = "docs/ROUTES.md"
const HTTP_METHODS = [
  "GET",
  "POST",
  "PUT",
  "PATCH",
  "DELETE",
  "HEAD",
  "OPTIONS",
]

function listAppFiles() {
  const result = spawnSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "app"],
    { encoding: "utf8" }
  )
  if (result.status !== 0)
    throw new Error(`git ls-files failed: ${result.stderr}`)
  return result.stdout.split("\n").filter(Boolean)
}

function toRoutePath(file) {
  const segments = file
    .replace(/^app\//, "")
    .replace(/\/(page|route)\.(tsx?|jsx?)$/, "")
    .split("/")
    .filter((segment) => segment.length > 0 && !/^\(.*\)$/.test(segment))
  return "/" + segments.join("/")
}

function exportedMethods(source) {
  return HTTP_METHODS.filter((method) =>
    new RegExp(
      `export\\s+(?:async\\s+)?function\\s+${method}\\b|export\\s+const\\s+${method}\\b`
    ).test(source)
  )
}

function exportedActions(source) {
  const names = new Set()
  const re = /export\s+(?:async\s+)?function\s+([A-Za-z0-9_]+)/g
  for (const match of source.matchAll(re)) names.add(match[1])
  return [...names].sort()
}

const files = listAppFiles()
const pages = []
const handlers = []
const actions = []

for (const file of files) {
  if (/\/page\.(tsx?|jsx?)$/.test(file)) {
    pages.push(toRoutePath(file) || "/")
  } else if (/\/route\.(tsx?|jsx?)$/.test(file)) {
    const methods = exportedMethods(readFileSync(file, "utf8"))
    handlers.push({ path: toRoutePath(file) || "/", methods, file })
  } else if (/\/actions\.(tsx?|jsx?)$/.test(file)) {
    actions.push({ file, names: exportedActions(readFileSync(file, "utf8")) })
  }
}

pages.sort()
handlers.sort((a, b) => a.path.localeCompare(b.path))
actions.sort((a, b) => a.file.localeCompare(b.file))

const lines = []
lines.push("# Route contract")
lines.push("")
lines.push(
  "> Generated by `scripts/generate-route-contract.mjs` from the App Router file"
)
lines.push(
  "> tree. Do not edit by hand — run `pnpm docs:routes` to regenerate."
)
lines.push("")
lines.push(`## Pages (${pages.length})`)
lines.push("")
for (const path of pages) lines.push(`- \`${path}\``)
lines.push("")
lines.push(`## Route handlers (${handlers.length})`)
lines.push("")
lines.push("| Route | Methods |")
lines.push("| ----- | ------- |")
for (const { path, methods } of handlers) {
  lines.push(`| \`${path}\` | ${methods.join(", ") || "—"} |`)
}
lines.push("")
lines.push(`## Server-action modules (${actions.length})`)
lines.push("")
for (const { file, names } of actions) {
  lines.push(
    `- \`${file}\` — ${names.map((name) => `\`${name}\``).join(", ") || "—"}`
  )
}
lines.push("")

const content = lines.join("\n")
const isCheck = process.argv.includes("--check")

if (isCheck) {
  let current = ""
  try {
    current = readFileSync(OUTPUT, "utf8")
  } catch {
    current = ""
  }
  if (current !== content) {
    console.error(
      `${OUTPUT} is out of date. Run \`pnpm docs:routes\` and commit the result.`
    )
    process.exit(1)
  }
  console.log(
    `${OUTPUT} is up to date (${pages.length} pages, ${handlers.length} handlers).`
  )
} else {
  writeFileSync(OUTPUT, content)
  console.log(
    `Wrote ${OUTPUT}: ${pages.length} pages, ${handlers.length} route handlers, ${actions.length} action modules.`
  )
}
